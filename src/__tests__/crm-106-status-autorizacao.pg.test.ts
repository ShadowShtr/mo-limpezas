describe("1-3. o resolver exige estado activo", () => {
  it("🔴 1. ACTIVO resolve o seu profile id", LENTO, async () => {
    expect(await resolver(ATIVA)).toBe(ATIVA);
    expect(await resolver(GESTORA)).toBe(GESTORA);
  });

  it("🔴 2. SUSPENSO não resolve", LENTO, async () => {
    expect(await resolver(SUSPENSA)).toBeNull();
  });

  it("🔴 3. INATIVO não resolve", LENTO, async () => {
    expect(await resolver(INATIVA)).toBeNull();
  });

  it("sem sessão, continua a devolver NULL", LENTO, async () => {
    expect(await resolver(null)).toBeNull();
  });

  it("🔴 a transição é imediata: suspender tira o acesso à consulta seguinte", LENTO, async () => {
    // 🔴 Não há cache, não há sessão a expirar, não há nada a limpar. O token
    //    da pessoa continua válido; o que mudou foi a resposta da base.
    expect(await resolver(ATIVA)).toBe(ATIVA);
    await pool.query("UPDATE public.profiles SET status = 'suspenso' WHERE id = $1", [ATIVA]);
    expect(await resolver(ATIVA)).toBeNull();
    await pool.query("UPDATE public.profiles SET status = 'ativo' WHERE id = $1", [ATIVA]);
    expect(await resolver(ATIVA)).toBe(ATIVA);
  });

  it("🔴 um estado que o CHECK não conhece não resolve (forma FECHADA)", LENTO, async () => {
    // Não se consegue gravar um estado fora do CHECK — e é isso mesmo. O que
    // este ensaio fixa é o desenho: a regra é `= 'ativo'`, não uma lista de
    // proibidos. Um estado novo nasce SEM acesso.
    await expect(
      pool.query("UPDATE public.profiles SET status = 'arquivado' WHERE id = $1", [ATIVA]),
    ).rejects.toThrow(/profiles_status_check|violates check constraint/);

    const { rows } = await pool.query(
      "SELECT prosrc FROM pg_proc WHERE oid = to_regprocedure($1)", [SIG_RESOLVER]);
    expect(String(rows[0].prosrc)).toMatch(/status\s*=\s*'ativo'/);
    expect(String(rows[0].prosrc)).not.toMatch(/status\s*(<>|!=)/);
    expect(String(rows[0].prosrc)).not.toMatch(/NOT IN|lower\(|btrim\(|trim\(/);
  });
});

