/**
 * Corre uma consulta COMO uma pessoa autenticada.
 *
 * 🔴 `SET LOCAL request.jwt.claim.sub` é o que o `auth.uid()` do palco lê — a
 *    mesma forma que o PostgREST usa. É assim que se simula um TOKEN JÁ
 *    EMITIDO: o JWT é perfeitamente válido e não se sabe nada sobre o estado
 *    do perfil. Se a pessoa perder acesso, é a base a decidir, não o login.
 */
async function comoUtilizador<T>(
  authUid: string | null,
  sql: string,
  params: unknown[] = [],
  papel = "authenticated",
): Promise<T[]> {
  const c = new pg.Client({ ...container.connection });
  await c.connect();
  try {
    await c.query("BEGIN");
    await c.query(`SET LOCAL request.jwt.claim.sub = '${authUid ?? ""}'`);
    await c.query(`SET LOCAL ROLE ${papel}`);
    const { rows } = await c.query(sql, params);
    await c.query("ROLLBACK");
    return rows as T[];
  } finally {
    await c.end();
  }
}

const resolver = async (uid: string | null): Promise<string | null> => {
  const rows = await comoUtilizador<{ id: string | null }>(
    uid, "SELECT public.get_my_profile_id() AS id");
  return rows[0].id;
};

const empresaDe = async (uid: string | null): Promise<string | null> => {
  const rows = await comoUtilizador<{ c: string | null }>(
    uid, "SELECT public.get_my_company_id() AS c");
  return rows[0].c;
};

const papelDe = async (uid: string | null): Promise<string | null> => {
  const rows = await comoUtilizador<{ r: string | null }>(
    uid, "SELECT public.get_my_role() AS r");
  return rows[0].r;
};

const podeVerServico = async (uid: string | null, servico: string): Promise<boolean> => {
  const rows = await comoUtilizador<{ ok: boolean }>(
    uid, "SELECT public.can_access_service($1) AS ok", [servico]);
  return rows[0].ok;
};

