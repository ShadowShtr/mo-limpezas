const lerSql = (rel: string) => readFileSync(join(process.cwd(), rel), "utf8");

const checksumLf = (ficheiro: string): string =>
  createHash("sha256")
    .update(lerSql(`supabase/migrations/${ficheiro}`).split("\r\n").join("\n").split("\r").join("\n"))
    .digest("hex");

async function registarNoLedger(nome: string, checksum?: string): Promise<void> {
  await pool.query(
    `INSERT INTO public._migrations (name, checksum) VALUES ($1,$2)
     ON CONFLICT (name) DO UPDATE SET checksum = EXCLUDED.checksum`,
    [nome, checksum ?? checksumLf(nome)],
  );
}

/** A cadeia de identidade. `aplicar106` fecha o palco com a migration em prova. */
async function palco(aplicar106 = true): Promise<void> {
  await pool.query("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;");
  await pool.query("DROP SCHEMA IF EXISTS auth CASCADE;");
  await pool.query(baselineCompleto());
  await pool.query("ALTER ROLE service_role BYPASSRLS;");
  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS clients_id_company_unique ON public.clients (id, company_id);
    ALTER TABLE public.data_history ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    CREATE OR REPLACE FUNCTION public.update_updated_at() RETURNS TRIGGER AS $upd$
      BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $upd$ LANGUAGE plpgsql;
    CREATE OR REPLACE FUNCTION public.fn_capture_history() RETURNS trigger
      LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $h$
      BEGIN RETURN COALESCE(NEW, OLD); END; $h$;
  `);
  // 🔴 O default privilege do projecto: uma função nova nasce executável por
  //    anon/authenticated/service_role. É contra isto que a ACL da 106 tem de
  //    trabalhar — sem isto no palco, a ACL passaria por acidente.
  await pool.query(`
    ALTER DEFAULT PRIVILEGES IN SCHEMA public
      GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;
  `);

  // 🔴 O CHECK de `profiles.status`, que o fixture NÃO traz.
  //
  //    `production-schema-shape.sql` é gerado por introspecção e extrai
  //    tabelas, colunas, PK/FK, RLS e políticas — não esta restrição. Mas ela
  //    EXISTE em produção, lida no catálogo vivo a 2026-09-24:
  //
  //        CHECK (status = ANY (ARRAY['ativo', 'inativo', 'suspenso']))
  //
  //    Acrescentá-la aqui não é fabricar a precondição que a migration testa —
  //    é completar o palco com o que produção provadamente tem e o dump não
  //    copia. Sem ela, o ensaio do estado fora do domínio não mede nada (um
  //    UPDATE para 'arquivado' passaria) e a precondição da 106 recusaria a
  //    instalação por um motivo que produção não tem.
  await pool.query(`
    ALTER TABLE public.profiles
      ADD CONSTRAINT profiles_status_check
      CHECK (status = ANY (ARRAY['ativo'::text, 'inativo'::text, 'suspenso'::text]));
  `);

  // 🔴 A `can_access_service` REAL da 034, e não o coto do baseline.
  //
  //    `production-baseline.ts` cria-a como `SELECT true` — um coto suficiente
  //    para outras suites, e inútil para esta: mediria sempre `true` e as
  //    provas 9-11 davam verde sem tocar em lógica nenhuma.
  //
  //    O corpo abaixo é COPIADO da 034, que é quem a cria em produção — a
  //    mesma prática do `HELPERS_PARA_CRM` do harness, que copia os corpos
  //    reais das migrations que os criam em vez de inventar versões
  //    simplificadas. É a forma ANTERIOR à 106, com `p.id = auth.uid()` e sem
  //    `search_path`: é isso que a 106 tem de encontrar e corrigir.
  await pool.query(`
    CREATE OR REPLACE FUNCTION public.can_access_service(p_service_id uuid)
    RETURNS boolean
    LANGUAGE sql
    SECURITY DEFINER
    STABLE
    AS $can$
      SELECT EXISTS (
        SELECT 1
        FROM   services s
        INNER  JOIN profiles p ON p.id = auth.uid() AND p.company_id = s.company_id
        WHERE  s.id = p_service_id
        AND (
          EXISTS (
            SELECT 1 FROM team_members tm
            WHERE  tm.team_id        = s.team_id
            AND    tm.collaborator_id = auth.uid()
            AND   (tm.left_at IS NULL OR tm.left_at > NOW())
          )
          OR EXISTS (
            SELECT 1 FROM service_reinforcements sr
            WHERE  sr.service_id     = s.id
            AND    sr.collaborator_id = auth.uid()
          )
        )
      )
    $can$;
    GRANT EXECUTE ON FUNCTION public.can_access_service(uuid) TO PUBLIC;
    -- 🔴 E os três papéis do Supabase, EXPLICITAMENTE.
    --
    --    O baseline cria a função ANTES de o \`ALTER DEFAULT PRIVILEGES\` estar
    --    em vigor, e \`CREATE OR REPLACE\` preserva a ACL existente — por isso o
    --    palco ficava com \`{PUBLIC, postgres}\` enquanto produção tem
    --    \`{PUBLIC, anon, authenticated, postgres, service_role}\`, lido no
    --    catálogo vivo. Sem isto, o pré-estado da 106 recusava-se a instalar
    --    aqui por uma diferença que produção não tem.
    GRANT EXECUTE ON FUNCTION public.can_access_service(uuid) TO anon, authenticated, service_role;
  `);

  for (const m of MIGRATIONS_CRM) await pool.query(migrationCrm(m));
  await pool.query(lerSql(M_101B));

  // 🔴 O comentario vivo do resolver. A 101b cria-o com um texto ACENTUADO;
  //    producao tem um SEM acentos, mais curto. O palco copia o que la esta,
  //    senao o pre-estado da 106 recusava-se a instalar aqui por uma diferenca
  //    que producao nao tem.
  //
  //    `can_access_service` fica SEM comentario, como em producao.
  //    `COMMENT ON` e DDL: nao aceita $1. Dai a interpolacao — a constante nao
  //    tem plicas nem vem de fora.
  await pool.query(
    "COMMENT ON FUNCTION public.get_my_profile_id() IS '" + COMENTARIO_PREDECESSOR + "'");
  await pool.query("COMMENT ON FUNCTION public.can_access_service(uuid) IS NULL");

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public._migrations (
      name text PRIMARY KEY, checksum text, applied_at timestamptz NOT NULL DEFAULT now())`);
  for (const nome of CADEIA) await registarNoLedger(nome);

  await semear();

  if (aplicar106) {
    await pool.query(lerSql(M_106));
    await registarNoLedger(NOME_106);
  }
}

