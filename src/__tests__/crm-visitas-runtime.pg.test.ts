describe("a fronteira com a operação", () => {
  it("🔴 marcar e fechar visitas não cria serviços, contratos nem locais", LENTO, async () => {
    const v = await marcar();
    await fechar(pool, v, "realizada");
    await marcar({ lead_id: null, client_id: CLIENTE_A });

    for (const t of ["services", "contracts", "locations", "invoices", "cash_flow_entries"]) {
      const { rows } = await pool.query(`SELECT count(*)::int n FROM public.${t}`);
      expect(rows[0].n, `${t} devia continuar vazia`).toBe(0);
    }
  });
});
