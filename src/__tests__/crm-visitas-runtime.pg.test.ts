describe("a quem se vai — lead OU cliente", () => {
  it("só lead: aceite", LENTO, async () => {
    expect(await marcar({ lead_id: leadA, client_id: null })).toBeTruthy();
  });

  it("🔴 só cliente: aceite — era a metade do modelo que o formulário não usava", LENTO, async () => {
    expect(await marcar({ lead_id: null, client_id: CLIENTE_A })).toBeTruthy();
  });

  it("🔴 lead E cliente: recusado", LENTO, async () => {
    await expect(marcar({ lead_id: leadA, client_id: CLIENTE_A }))
      .rejects.toThrow(/crm_visits_um_destinatario/);
  });

  it("🔴 nem lead nem cliente: recusado", LENTO, async () => {
    await expect(marcar({ lead_id: null, client_id: null }))
      .rejects.toThrow(/crm_visits_um_destinatario/);
  });

  it("a janela tem de fazer sentido", LENTO, async () => {
    const agora = new Date();
    await expect(marcar({
      scheduled_start: agora.toISOString(),
      scheduled_end: new Date(agora.getTime() - 60_000).toISOString(),
    })).rejects.toThrow(/crm_visits_janela_valida/);
  });
});

