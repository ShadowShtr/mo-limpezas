describe("isolamento por empresa", () => {
  it("🔴 cliente de outra empresa: recusado pela FK composta", LENTO, async () => {
    await expect(marcar({ lead_id: null, client_id: CLIENTE_B })).rejects.toThrow();
  });

  it("🔴 responsável de outra empresa: recusado", LENTO, async () => {
    await expect(marcar({ assigned_to: GESTORA_OUTRA })).rejects.toThrow();
  });

  it("🔴 a gestora da outra empresa não vê estas visitas", LENTO, async () => {
    await marcar();
    const c = new pg.Client({ ...container.connection });
    await c.connect();
    try {
      await c.query("SELECT set_config('request.jwt.claim.sub', $1, false)", [GESTORA_OUTRA]);
      await c.query("SET ROLE authenticated");
      const { rows } = await c.query("SELECT count(*)::int n FROM public.crm_visits");
      expect(rows[0].n).toBe(0);
    } finally { await c.end(); }
  });

  it("🔴 uma colaboradora não vê a agenda comercial", LENTO, async () => {
    await marcar();
    const c = new pg.Client({ ...container.connection });
    await c.connect();
    try {
      await c.query("SELECT set_config('request.jwt.claim.sub', $1, false)", [COLAB]);
      await c.query("SET ROLE authenticated");
      const { rows } = await c.query("SELECT count(*)::int n FROM public.crm_visits");
      expect(rows[0].n).toBe(0);
    } finally { await c.end(); }
  });

  it("a gestora da empresa vê as suas", LENTO, async () => {
    await marcar();
    const c = new pg.Client({ ...container.connection });
    await c.connect();
    try {
      await c.query("SELECT set_config('request.jwt.claim.sub', $1, false)", [GESTORA]);
      await c.query("SET ROLE authenticated");
      const { rows } = await c.query("SELECT count(*)::int n FROM public.crm_visits");
      expect(rows[0].n).toBe(1);
    } finally { await c.end(); }
  });
});

