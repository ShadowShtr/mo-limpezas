describe("ciclo de vida — fechar é de ida", () => {
  for (const destino of VISIT_CLOSING_STATUSES) {
    it(`agendada → ${destino}`, LENTO, async () => {
      const v = await marcar();
      expect(await fechar(pool, v, destino)).toBe(v);
      const { rows } = await pool.query("SELECT status FROM public.crm_visits WHERE id=$1", [v]);
      expect(rows[0].status).toBe(destino);
    });
  }

  it("🔴 uma visita já fechada não volta a ser fechada", LENTO, async () => {
    const v = await marcar();
    expect(await fechar(pool, v, "realizada")).toBe(v);

    // Segunda tentativa: zero linhas. A action traduz isto em CONFLICT.
    expect(await fechar(pool, v, "cancelada")).toBeNull();

    const { rows } = await pool.query(
      "SELECT status, completed_at, cancelled_at FROM public.crm_visits WHERE id=$1", [v]);
    expect(rows[0].status).toBe("realizada");
    expect(rows[0].completed_at).not.toBeNull();
    expect(rows[0].cancelled_at).toBeNull();
  });

  // -------------------------------------------------------------------------
  // 🔴 A CORRIDA. Sem a condição `status = 'agendada'` dentro do UPDATE, os
  //    dois ganham e o último a escrever apaga o desfecho do primeiro.
  // -------------------------------------------------------------------------
  it("🔴 dois gestores a fechar ao mesmo tempo: só um ganha", LENTO, async () => {
    const v = await marcar();

    const a = new pg.Client({ ...container.connection });
    const b = new pg.Client({ ...container.connection });
    await a.connect();
    await b.connect();

    try {
      await a.query("BEGIN");
      await b.query("BEGIN");

      // A fecha como realizada e segura o lock de linha, sem commitar.
      const ganhouA = await fechar(a, v, "realizada");
      expect(ganhouA).toBe(v);

      // B tenta fechar como cancelada: fica à espera do lock de A.
      const tentativaB = fechar(b, v, "cancelada");
      await new Promise((r) => setTimeout(r, 800));

      await a.query("COMMIT");

      // Ao acordar, B relê a linha já com `realizada` e a condição falha.
      expect(await tentativaB).toBeNull();
      await b.query("COMMIT");
    } finally {
      await a.end().catch(() => { /* já fechada */ });
      await b.end().catch(() => { /* já fechada */ });
    }

    const { rows } = await pool.query(
      "SELECT status, cancelled_at FROM public.crm_visits WHERE id=$1", [v]);
    expect(rows[0].status).toBe("realizada");
    expect(rows[0].cancelled_at).toBeNull();
  });

  it("um desfecho sem data é recusado pela base", LENTO, async () => {
    const v = await marcar();
    await expect(
      pool.query("UPDATE public.crm_visits SET status='realizada' WHERE id=$1", [v]),
    ).rejects.toThrow(/crm_visits_realizada_tem_data/);
  });
});

