describe("🔴 rascunho → enviado, MANUALMENTE", () => {
  it("o estado muda e a data de envio é carimbada pela base", LENTO, async () => {
    // O envio automático é a 103-B2. Sem esta transição, um orçamento
    // entregue por PDF ficaria eternamente «rascunho».
    const { id } = await criar({
      itens: [{ description: "A", quantity: 1, unit: "servico", unit_price: 80 }],
    });
    expect(await estado(id)).toBe("rascunho");

    expect((await mudar(id, "enviado")).ok).toBe(true);

    const { rows } = await pool.query(
      "SELECT status, sent_at FROM public.crm_quotes WHERE id = $1", [id]);
    expect(rows[0].status).toBe("enviado");
    // O CHECK `crm_quotes_enviado_tem_data` não deixaria passar sem data.
    expect(rows[0].sent_at).not.toBeNull();
  });

  it("um enviado que expirou não se aceita", LENTO, async () => {
    const { id } = await criar({
      itens: [{ description: "A", quantity: 1, unit: "servico", unit_price: 80 }],
      validadeDias: 0,
    });
    await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,'enviado',NULL)", [EMPRESA, id, GESTORA]);
    // 🔴 As DUAS datas recuam. `crm_quotes_validade_coerente` exige
    //    `valid_until >= issue_date`, e mexer só na validade viola o CHECK —
    //    o ensaio rebentava antes de chegar à regra que quer medir.
    await pool.query(
      `UPDATE public.crm_quotes
          SET issue_date = CURRENT_DATE - 10, valid_until = CURRENT_DATE - 1
        WHERE id = $1`, [id]);

    const r = await mudar(id, "aceite");
    expect(r.ok).toBe(false);
    expect(r.ok === false && r.erro).toContain("QUOTE_EXPIRED_CANNOT_ACCEPT");
  });
});

