interface LinhaItem {
  description: string;
  quantity: number;
  unit: string;
  unit_price: number;
}

/**
 * `create_crm_quote_with_items` com os 19 argumentos, pela ordem da assinatura.
 *
 * 🔴 `p_prefix`, `p_year` e `p_vat_rate` são os mesmos que a Server Action
 *    passa: prefixo das definições, ano da data de emissão, taxa das
 *    definições. Um ensaio que passasse outros valores mediria outra coisa.
 */
async function criar(opts: {
  itens: LinhaItem[];
  desconto?: number;
  aplicaIva?: boolean;
  taxaIva?: number;
  validadeDias?: number;
}): Promise<{ id: string; numero: string }> {
  const { rows } = await pool.query(
    `SELECT * FROM public.create_crm_quote_with_items(
       $1,$2,NULL,NULL,'ORC',$3,CURRENT_DATE,CURRENT_DATE + $4::int,
       'pontual',$5,$6,$7,NULL,NULL,NULL,NULL,NULL,$8,$9::jsonb)`,
    [
      EMPRESA,
      leadA,
      ANO,
      opts.validadeDias ?? 30,
      opts.desconto ?? 0,
      opts.aplicaIva ?? true,
      opts.taxaIva ?? 23,
      GESTORA,
      JSON.stringify(opts.itens),
    ],
  );
  return { id: rows[0].quote_id as string, numero: rows[0].quote_number as string };
}

async function estado(id: string): Promise<string> {
  const { rows } = await pool.query("SELECT status FROM public.crm_quotes WHERE id = $1", [id]);
  return rows[0].status as string;
}

/** `set_crm_quote_status`, devolvendo se a base aceitou ou porque recusou. */
async function mudar(
  id: string,
  destino: string,
): Promise<{ ok: true } | { ok: false; erro: string }> {
  try {
    await pool.query(
      "SELECT * FROM public.set_crm_quote_status($1,$2,$3,$4,NULL)",
      [EMPRESA, id, GESTORA, destino],
    );
    return { ok: true };
  } catch (err) {
    return { ok: false, erro: String((err as Error).message) };
  }
}

/** Põe um orçamento novo no estado pedido, pelo caminho que a base permite. */
async function orcamentoEm(destino: QuoteStatus): Promise<string> {
  const { id } = await criar({ itens: [{ description: "Base", quantity: 1, unit: "servico", unit_price: 100 }] });
  if (destino === "rascunho") return id;
  if (destino === "anulado") {
    await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,'anulado',NULL)", [EMPRESA, id, GESTORA]);
    return id;
  }
  // Tudo o resto passa por `enviado`.
  await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,'enviado',NULL)", [EMPRESA, id, GESTORA]);
  if (destino === "enviado") return id;
  await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,$4,NULL)", [EMPRESA, id, GESTORA, destino]);
  return id;
}

