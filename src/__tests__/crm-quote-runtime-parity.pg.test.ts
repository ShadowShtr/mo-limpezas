// ============================================================================
// Orçamentos — o runtime contra a base a sério
// ============================================================================
//
// 🔴 O que só Postgres real responde, e nenhum mock responde.
//
//    1. os TOTAIS. `totaisDoOrcamento` existe para antecipar no ecrã o que a
//       RPC vai gravar. Se divergir num cêntimo, o formulário promete um valor
//       e o documento diz outro — e quem recebe o PDF não sabe qual é o certo.
//       Um mock da RPC compararia a função consigo mesma.
//
//    2. a MATRIZ DE ESTADOS. `QUOTE_TRANSITIONS` é espelho de
//       `set_crm_quote_status`. `crm-quotes-vocabulary.test.ts` compara-a com o
//       TEXTO do SQL; aqui compara-se com o COMPORTAMENTO: os 36 pares
//       possíveis, um a um, contra a base. Um `IF` que o regexp leu bem mas
//       que a base avalia de outra maneira passaria pelo primeiro e cai aqui.
//
//    3. o FLUXO DE REVISÃO. Que uma R1 nasce em rascunho e a R0 fica marcada
//       como substituída, na mesma transação, é propriedade da RPC — não se
//       demonstra com texto no ecrã a dizer que acontece.
//
// O palco é a cadeia como está em produção HOJE: baseline + 101 + 101a + 101b
// + 102 → 103.
// ============================================================================

