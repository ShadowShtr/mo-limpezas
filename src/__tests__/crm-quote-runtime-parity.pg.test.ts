describe("🔴 paridade de estados — os 36 pares, um a um", () => {
  for (const origem of QUOTE_STATUSES) {
    for (const destino of QUOTE_STATUSES) {
      if (origem === destino) continue; // idempotente por desenho da RPC

      const permitido = canTransitionQuote(origem, destino);

      it(`${origem} → ${destino}: ${permitido ? "aceite" : "recusado"}`, LENTO, async () => {
        const id = await orcamentoEm(origem);
        expect(await estado(id), `o palco não pôs o orçamento em ${origem}`).toBe(origem);

        const r = await mudar(id, destino);

        expect(r.ok, `runtime diz ${permitido}, base diz ${r.ok}`).toBe(permitido);
        if (permitido) {
          expect(await estado(id)).toBe(destino);
        } else {
          // Recusada é recusada: o estado não se move nem um pouco.
          expect(await estado(id)).toBe(origem);
          expect(
            r.ok === false && /QUOTE_(TRANSITION_NOT_ALLOWED|ACCEPTED|VOIDED|EXPIRED)/.test(r.erro),
          ).toBe(true);
        }
      });
    }
  }

  it("o mesmo estado outra vez é aceite sem mudar nada", LENTO, async () => {
    const id = await orcamentoEm("enviado");
    const { rows: antes } = await pool.query(
      "SELECT sent_at FROM public.crm_quotes WHERE id = $1", [id]);
    expect((await mudar(id, "enviado")).ok).toBe(true);
    const { rows: depois } = await pool.query(
      "SELECT sent_at FROM public.crm_quotes WHERE id = $1", [id]);
    expect(depois[0].sent_at).toEqual(antes[0].sent_at);
  });
});

