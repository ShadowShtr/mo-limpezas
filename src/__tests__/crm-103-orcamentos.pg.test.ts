/** `create_crm_quote_with_items` com os 19 argumentos, pela ordem da assinatura. */
async function criar(
  c: pg.Pool | pg.Client,
  over: { leadId?: string | null; clientId?: string | null; empresa?: string; ano?: number } = {},
): Promise<{ id: string; numero: string }> {
  const { rows } = await c.query(
    `SELECT * FROM public.create_crm_quote_with_items(
       $1,$2,$3,NULL,'ORC',$4,CURRENT_DATE,CURRENT_DATE + 30,
       'pontual',0,true,23,NULL,NULL,NULL,NULL,NULL,$5,$6::jsonb)`,
    [
      over.empresa ?? EMPRESA,
      over.leadId === undefined ? leadA : over.leadId,
      over.clientId ?? null,
      over.ano ?? ANO,
      GESTORA,
      ITENS,
    ],
  );
  return { id: rows[0].quote_id as string, numero: rows[0].quote_number as string };
}

async function ligacao(): Promise<pg.Client> {
  const c = new pg.Client({ ...container.connection });
  await c.connect();
  return c;
}

