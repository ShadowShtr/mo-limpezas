// 🔴 EFEITO PARCIAL. Uma aplicação interrompida a meio, ou um rollback manual
//    que apagou a tabela e esqueceu as RPC, deixa metade da 103 de pé. Um
//    portão que só perguntasse por `crm_quotes` adoptava esse meio-estado — e
//    um `CREATE OR REPLACE FUNCTION` por cima de uma RPC de outra versão não
//    dá erro nenhum, fica só errado.
// ---------------------------------------------------------------------------
describe("efeito parcial também é efeito", () => {
  /** Cada vestígio exclusivo da 103, sozinho, tem de travar a migration. */
  const VESTIGIOS: ReadonlyArray<readonly [string, string]> = [
    ["só a tabela de linhas", `
      CREATE TABLE public.crm_quote_items (id uuid PRIMARY KEY)`],
    ["só um índice exclusivo", `
      CREATE TABLE public.sobra_103 (id uuid, company_id uuid);
      CREATE UNIQUE INDEX uq_crm_quotes_numero ON public.sobra_103 (id)`],
    ["só a RPC de criação", `
      CREATE FUNCTION public.create_crm_quote_with_items(
        p_company_id uuid, p_lead_id uuid, p_client_id uuid, p_visit_id uuid,
        p_prefix text, p_year integer, p_issue_date date, p_valid_until date,
        p_pricing_kind text, p_discount_pct numeric, p_apply_vat boolean,
        p_vat_rate numeric, p_proposed_frequency text, p_proposed_weekdays jsonb,
        p_payment_terms text, p_notes text, p_internal_notes text, p_actor uuid,
        p_items jsonb)
      RETURNS TABLE (quote_id uuid, quote_number text)
      LANGUAGE sql AS $f$ SELECT NULL::uuid, NULL::text $f$`],
    ["só o trigger de proveniência", `
      CREATE FUNCTION public.crm_quotes_proveniencia_imutavel()
      RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN RETURN NEW; END; $f$`],
  ];

  for (const [nome, ddl] of VESTIGIOS) {
    it(`🔴 ${nome}: REJEITADO, e o vestígio fica intacto`, LENTO, async () => {
      await palco(false);
      await pool.query(ddl);

      await expect(pool.query(lerSql(M_103)))
        .rejects.toThrow(/EFFECT_WITHOUT_LEDGER/);

      // Zero mutações: a tabela principal não chegou a nascer.
      const { rows } = await pool.query(`
        SELECT to_regclass('public.crm_quotes') AS q,
               (SELECT count(*)::int FROM public._migrations
                 WHERE name=$1) AS ledger`, [NOME_103]);
      expect(rows[0].q).toBeNull();
      expect(rows[0].ledger).toBe(0);
    });
  }

  // 🔴 A ÚNICA excepção, e tem de ser provada como excepção.
  //
  //    O rollback deixa `company_settings.quote_prefix` de propósito. Se essa
  //    coluna contasse como efeito parcial, o estado normal depois de um
  //    rollback limpo seria lido como meio-aplicado e a 103 nunca mais poderia
  //    ser reaplicada — um portão que se tranca a si próprio.
  it("quote_prefix sozinho NÃO conta como efeito — é a excepção documentada", LENTO, async () => {
    await palco(false);
    await pool.query(
      "ALTER TABLE public.company_settings ADD COLUMN IF NOT EXISTS quote_prefix text NOT NULL DEFAULT 'ORC'");

    await pool.query(lerSql(M_103));
    const { rows } = await pool.query("SELECT to_regclass('public.crm_quotes') AS q");
    expect(rows[0].q).toBe("crm_quotes");
  });
});

// ---------------------------------------------------------------------------
// 🔴 SOURCE_LEAD_IMMUTABILITY. A versão da branch ampla só protegia quando
//    `OLD.source_lead_id IS NOT NULL`, para deixar passar um backfill. Isso
//    abria `NULL → valor`: um caminho de escrita futuro podia atribuir a um
//    orçamento uma lead de origem que ele nunca teve, meses depois, sem rasto.
// ---------------------------------------------------------------------------
describe("proveniência do orçamento não se reescreve", () => {
  beforeEach(async () => { await palco(true); }, 120_000);

  it("nasce igual à lead de origem", LENTO, async () => {
    const q = await criar(pool);
    const { rows } = await pool.query(
      "SELECT source_lead_id FROM public.crm_quotes WHERE id=$1", [q.id]);
    expect(rows[0].source_lead_id).toBe(leadA);
  });

  it("🔴 valor → outro: REJECT", LENTO, async () => {
    const q = await criar(pool);
    const { rows } = await pool.query(
      "INSERT INTO public.crm_leads (company_id,name) VALUES ($1,'Outra') RETURNING id", [EMPRESA]);
    await expect(
      pool.query("UPDATE public.crm_quotes SET source_lead_id=$1 WHERE id=$2", [rows[0].id, q.id]),
    ).rejects.toThrow(/QUOTE_SOURCE_LEAD_IMMUTABLE/);
  });

  it("🔴 valor → NULL: REJECT", LENTO, async () => {
    const q = await criar(pool);
    await expect(
      pool.query("UPDATE public.crm_quotes SET source_lead_id=NULL WHERE id=$1", [q.id]),
    ).rejects.toThrow(/QUOTE_SOURCE_LEAD_IMMUTABLE/);
  });

  it("🔴 NULL → valor: REJECT — era a brecha do backfill", LENTO, async () => {
    // Um orçamento a um cliente nasce sem lead de origem.
    const q = await criar(pool, { leadId: null, clientId: CLIENTE_A });
    const { rows: antes } = await pool.query(
      "SELECT source_lead_id FROM public.crm_quotes WHERE id=$1", [q.id]);
    expect(antes[0].source_lead_id).toBeNull();

    await expect(
      pool.query("UPDATE public.crm_quotes SET source_lead_id=$1 WHERE id=$2", [leadA, q.id]),
    ).rejects.toThrow(/QUOTE_SOURCE_LEAD_IMMUTABLE/);
  });

  it("NULL → NULL: passa (não é mudança)", LENTO, async () => {
    const q = await criar(pool, { leadId: null, clientId: CLIENTE_A });
    await pool.query("UPDATE public.crm_quotes SET notes='sem tocar na origem' WHERE id=$1", [q.id]);
    const { rows } = await pool.query(
      "SELECT source_lead_id, notes FROM public.crm_quotes WHERE id=$1", [q.id]);
    expect(rows[0].source_lead_id).toBeNull();
    expect(rows[0].notes).toBe("sem tocar na origem");
  });
});

// ---------------------------------------------------------------------------
// 🔴 NUMERAÇÃO CONCORRENTE. Sem o `pg_advisory_xact_lock`, duas criações
//    simultâneas leem o mesmo MAX e pedem o mesmo `quote_seq`. O índice único
//    apanharia a colisão — mas como erro incompreensível ao utilizador, e
//    repetível a cada tentativa.
// ---------------------------------------------------------------------------
describe("numeração concorrente", () => {
  beforeEach(async () => { await palco(true); }, 120_000);

  it("🔴 duas criações simultâneas: números diferentes e consecutivos", LENTO, async () => {
    const a = await ligacao();
    const b = await ligacao();
    try {
      await a.query("BEGIN");
      await b.query("BEGIN");

      // A pega no lock da empresa+ano e segura-o até ao commit.
      const qa = await criar(a);

      // B arranca e fica pendurado no advisory lock.
      const pendenteB = criar(b);
      await new Promise((r) => setTimeout(r, 600));
      await a.query("COMMIT");

      const qb = await pendenteB;
      await b.query("COMMIT");

      expect(qa.numero).not.toBe(qb.numero);
      expect([qa.numero, qb.numero].sort()).toEqual(["ORC2026/001", "ORC2026/002"]);
    } finally {
      await a.end().catch(() => { /* já fechada */ });
      await b.end().catch(() => { /* já fechada */ });
    }

    const { rows } = await pool.query(
      "SELECT array_agg(DISTINCT quote_seq ORDER BY quote_seq) AS seqs FROM public.crm_quotes");
    expect(rows[0].seqs.map(Number)).toEqual([1, 2]);
  });

  it("🔴 uma revisão NÃO consome sequencial", LENTO, async () => {
    const q1 = await criar(pool);
    expect(q1.numero).toBe("ORC2026/001");

    await pool.query(
      "SELECT public.set_crm_quote_status($1,$2,$3,'enviado',NULL)",
      [EMPRESA, q1.id, GESTORA]);

    const { rows: rev } = await pool.query(
      `SELECT * FROM public.revise_crm_quote(
         $1,$2,$3,CURRENT_DATE,CURRENT_DATE + 30,0,true,23,NULL,$4::jsonb)`,
      [EMPRESA, q1.id, GESTORA, ITENS]);
    expect(rev[0].quote_number).toBe("ORC2026/001-R1");

    const q2 = await criar(pool);
    expect(q2.numero).toBe("ORC2026/002");
  });
});

// ---------------------------------------------------------------------------
// 🔴 REVISÕES CONCORRENTES. Duas pessoas a rever a mesma revisão viva: se as
//    duas ganhassem, a raiz ficava com dois ramos vivos e ninguém saberia qual
//    é o orçamento em vigor.
// ---------------------------------------------------------------------------
describe("revisões concorrentes", () => {
  beforeEach(async () => { await palco(true); }, 120_000);

  it("🔴 duas revisões da mesma revisão viva: só uma ganha", LENTO, async () => {
    const q1 = await criar(pool);
    await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,'enviado',NULL)",
      [EMPRESA, q1.id, GESTORA]);

    const a = await ligacao();
    const b = await ligacao();
    let resultadoB: string | null = null;

    try {
      await a.query("BEGIN");
      await b.query("BEGIN");

      const revA = await a.query(
        `SELECT * FROM public.revise_crm_quote(
           $1,$2,$3,CURRENT_DATE,CURRENT_DATE + 30,0,true,23,NULL,$4::jsonb)`,
        [EMPRESA, q1.id, GESTORA, ITENS]);
      expect(revA.rows[0].quote_number).toBe("ORC2026/001-R1");

      const pendenteB = b.query(
        `SELECT * FROM public.revise_crm_quote(
           $1,$2,$3,CURRENT_DATE,CURRENT_DATE + 30,0,true,23,NULL,$4::jsonb)`,
        [EMPRESA, q1.id, GESTORA, ITENS],
      ).then(() => "passou").catch((e: Error) => e.message);

      await new Promise((r) => setTimeout(r, 600));
      await a.query("COMMIT");

      resultadoB = await pendenteB;
      await b.query("COMMIT").catch(() => b.query("ROLLBACK"));
    } finally {
      await a.end().catch(() => { /* já fechada */ });
      await b.end().catch(() => { /* já fechada */ });
    }

    // B não pode ter criado um segundo ramo vivo.
    expect(resultadoB).not.toBe("passou");

    const { rows } = await pool.query(
      `SELECT count(*)::int n FROM public.crm_quotes
        WHERE quote_seq = 1 AND superseded_by_id IS NULL`);
    expect(rows[0].n, "mais do que uma revisão viva na mesma raiz").toBe(1);
  });

  it("o índice de revisão viva existe e é único", LENTO, async () => {
    const { rows } = await pool.query(`
      SELECT indexdef FROM pg_indexes
       WHERE schemaname='public' AND indexname='uq_crm_quotes_revisao_viva'`);
    expect(rows).toHaveLength(1);
    expect(rows[0].indexdef).toContain("UNIQUE");
  });
});

