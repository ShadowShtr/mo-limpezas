describe("rollback", () => {
  const linhaLedger = async (): Promise<number> => {
    const { rows } = await pool.query(
      "SELECT count(*)::int n FROM public._migrations WHERE name=$1", [NOME_103]);
    return rows[0].n as number;
  };

  it("ROLLBACK_EMPTY: sem documentos e com prefixo intacto — desfaz tudo", LENTO, async () => {
    await palco(true);
    expect(await linhaLedger()).toBe(1);

    await pool.query(lerSql(ROLLBACK_103));

    const { rows } = await pool.query(`
      SELECT to_regclass('public.crm_quotes') AS q,
             to_regclass('public.crm_quote_items') AS i,
             to_regclass('public.crm_visits') AS v,
             to_regprocedure('public.crm_quotes_proveniencia_imutavel()') AS trg`);
    expect(rows[0].q).toBeNull();
    expect(rows[0].i).toBeNull();
    // 🔴 A 102 não vai atrás.
    expect(rows[0].v).toBe("crm_visits");
    expect(rows[0].trg).toBeNull();
    expect(await linhaLedger()).toBe(0);
  });

  it("🔴 ROLLBACK_WITH_DATA: um orçamento — RECUSADO, e nada se perde", LENTO, async () => {
    await palco(true);
    const q = await criar(pool);

    await expect(pool.query(lerSql(ROLLBACK_103))).rejects.toThrow(/ROLLBACK_RECUSADO/);

    const { rows } = await pool.query(
      "SELECT quote_number FROM public.crm_quotes WHERE id=$1", [q.id]);
    expect(rows).toHaveLength(1);
    expect(rows[0].quote_number).toBe("ORC2026/001");

    const { rows: itens } = await pool.query(
      "SELECT count(*)::int n FROM public.crm_quote_items WHERE quote_id=$1", [q.id]);
    expect(itens[0].n).toBeGreaterThan(0);

    expect(await linhaLedger(), "ledger intacto").toBe(1);
  });

  it("🔴 ROLLBACK_CONFIG_CHANGED: prefixo configurado — RECUSADO", LENTO, async () => {
    await palco(true);
    // Sem documentos nenhuns: só a configuração é que mudou.
    await pool.query("UPDATE public.company_settings SET quote_prefix='PROP' WHERE company_id=$1",
      [EMPRESA]);

    await expect(pool.query(lerSql(ROLLBACK_103))).rejects.toThrow(/ROLLBACK_CONFIG_ALTERADA/);

    const { rows } = await pool.query("SELECT to_regclass('public.crm_quotes') AS q");
    expect(rows[0].q).toBe("crm_quotes");
    expect(await linhaLedger(), "ledger intacto").toBe(1);

    const { rows: cfg } = await pool.query(
      "SELECT quote_prefix FROM public.company_settings WHERE company_id=$1", [EMPRESA]);
    expect(cfg[0].quote_prefix, "configuração preservada").toBe("PROP");
  });

  // -------------------------------------------------------------------------
  // 🔴 ROLLBACK_CONFIG_GUARD_ATOMIC.
  //
  //    Verificar o prefixo e desfazer a 103 são duas coisas; sem lock, cabe
  //    uma escrita entre elas:
  //
  //      T1 lê quote_prefix = 'ORC'  →  T2 grava 'PROP'  →  T1 desfaz a 103
  //
  //    T1 decidiu com informação velha: desfez sobre uma configuração que
  //    entretanto passou a existir. O `LOCK TABLE company_settings IN SHARE
  //    MODE` antes da leitura fecha a janela — o `UPDATE` de T2 espera.
  // -------------------------------------------------------------------------
  it("🔴 ROLLBACK_CONFIG_GUARD_ATOMIC: o prefixo não muda entre a guarda e o DROP", LENTO, async () => {
    await palco(true);

    const desfazedor = await ligacao();
    const utilizador = await ligacao();
    let resultadoUpdate: string | null = null;

    try {
      await desfazedor.query("BEGIN");

      // O rollback corre inteiro dentro da transação: pega no SHARE de
      // company_settings, conta, e larga as tabelas. Ainda não commitou.
      await desfazedor.query(lerSql(ROLLBACK_103));

      // Só agora o utilizador tenta configurar o prefixo. Fica à espera do
      // lock — não consegue entrar entre a guarda e o DROP.
      const pendente = utilizador.query(
        "UPDATE public.company_settings SET quote_prefix='PROP' WHERE company_id=$1",
        [EMPRESA],
      ).then(() => "entrou").catch((e: Error) => e.message);

      await new Promise((r) => setTimeout(r, 800));

      // A prova: enquanto o rollback segura o lock, o UPDATE não passou.
      const aindaPendente = await Promise.race([
        pendente,
        new Promise<string>((r) => setTimeout(() => r("ainda a espera"), 400)),
      ]);
      expect(aindaPendente, "o UPDATE entrou no meio do rollback").toBe("ainda a espera");

      await desfazedor.query("COMMIT");
      resultadoUpdate = await pendente;
    } finally {
      await desfazedor.end().catch(() => { /* já fechada */ });
      await utilizador.end().catch(() => { /* já fechada */ });
    }

    // Depois do commit o UPDATE segue — a 103 já foi desfeita com a leitura
    // que era verdade no momento da decisão.
    expect(resultadoUpdate).toBe("entrou");

    const { rows } = await pool.query(`
      SELECT to_regclass('public.crm_quotes') AS q,
             (SELECT quote_prefix FROM public.company_settings WHERE company_id=$1) AS prefixo`,
      [EMPRESA]);
    expect(rows[0].q).toBeNull();
    expect(rows[0].prefixo).toBe("PROP");
    expect(await linhaLedger()).toBe(0);
  });

  it("🔴 tabela alheia não é apagada por este rollback", LENTO, async () => {
    await palco(false);
    await pool.query("CREATE TABLE public.crm_quotes (id uuid PRIMARY KEY)");
    await expect(pool.query(lerSql(ROLLBACK_103))).rejects.toThrow(/TABELA_ALIENADA/);
    const { rows } = await pool.query("SELECT to_regclass('public.crm_quotes') AS q");
    expect(rows[0].q).toBe("crm_quotes");
  });

  it("🔴 ledger sem efeito não é arrumado em silêncio", LENTO, async () => {
    await palco(true);
    await pool.query("DROP TABLE public.crm_quote_items; DROP TABLE public.crm_quotes;");
    await expect(pool.query(lerSql(ROLLBACK_103)))
      .rejects.toThrow(/ROLLBACK_LEDGER_WITHOUT_EFFECT/);
    expect(await linhaLedger()).toBe(1);
  });

  it("🔴 checksum divergente: não desfaz o que não conhece", LENTO, async () => {
    await palco(true);
    await pool.query("UPDATE public._migrations SET checksum=$1 WHERE name=$2",
      ["0".repeat(64), NOME_103]);
    await expect(pool.query(lerSql(ROLLBACK_103)))
      .rejects.toThrow(/ROLLBACK_CHECKSUM_DIVERGENTE/);
  });

  it("sem tabela nem linha: no-op idempotente", LENTO, async () => {
    await palco(true);
    await pool.query(lerSql(ROLLBACK_103));
    await pool.query(lerSql(ROLLBACK_103));
    expect(await linhaLedger()).toBe(0);
  });

  it("depois do rollback, a 103 volta a aplicar-se com o prefixo já presente", LENTO, async () => {
    await palco(true);
    await pool.query(lerSql(ROLLBACK_103));

    // A coluna ficou — é a decisão documentada. Reaplicar tem de funcionar.
    const { rows: antes } = await pool.query(`
      SELECT count(*)::int n FROM information_schema.columns
       WHERE table_schema='public' AND table_name='company_settings' AND column_name='quote_prefix'`);
    expect(antes[0].n).toBe(1);

    await pool.query(lerSql(M_103));
    const { rows } = await pool.query("SELECT to_regclass('public.crm_quotes') AS q");
    expect(rows[0].q).toBe("crm_quotes");
  });
});
