// ============================================================================
// 103 — orçamentos: numeração, revisões e proveniência, contra Postgres real
// ============================================================================
//
// 🔴 O palco é a cadeia como ela está EM PRODUÇÃO hoje:
//
//        baseline canónico + 101 + 101a + 101b + 102  →  103
//
//    A 102 entrou no ledger a 19/09. A 103 depende dela — `crm_quotes.visit_id`
//    aponta para `crm_visits` — e o portão de proveniência exige as quatro.
//
// ---------------------------------------------------------------------------
// O que só Postgres real responde
// ---------------------------------------------------------------------------
//
//   · duas criações em simultâneo atribuem números diferentes e consecutivos;
//   · duas revisões da mesma revisão viva: só uma ganha;
//   · a proveniência não se reescreve, nem sequer de NULL para um valor.
//
// Nenhuma destas três se prova com mocks: são todas sobre o que acontece
// quando duas ligações fazem a mesma coisa ao mesmo tempo.
// ============================================================================

