/** O mesmo cálculo de `checksumForNewMigration`: SHA-256 sobre LF normalizado. */
const checksumLf = (ficheiro: string): string =>
  createHash("sha256")
    .update(lerSql(`supabase/migrations/${ficheiro}`).split("\r\n").join("\n").split("\r").join("\n"))
    .digest("hex");

/**
 * Escreve uma linha de ledger.
 *
 * 🔴 A ordem importa, e custou um vermelho a descobrir: a linha de uma
 *    migration só entra DEPOIS de ela correr. Escrever a da 102 antes de a
 *    aplicar dava `ledger=1 / tabela=0`, e o portão da própria 102 respondia
 *    `LEDGER_WITHOUT_EFFECT` — correctamente. O palco é que estava a encenar
 *    um estado que o runner nunca produz.
 */
async function registarNoLedger(nome: string, checksum?: string | null): Promise<void> {
  if (checksum === null) return; // linha deliberadamente em falta
  await pool.query(
    `INSERT INTO public._migrations (name, checksum) VALUES ($1,$2)
     ON CONFLICT (name) DO UPDATE SET checksum = EXCLUDED.checksum`,
    [nome, checksum ?? checksumLf(nome)],
  );
}

/** Cadeia real até à 102. `aplicar103` fecha o palco com a migration em prova. */
async function palco(aplicar103: boolean, ledger: Readonly<Record<string, string | null>> = {}): Promise<void> {
  await pool.query("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;");
  await pool.query("DROP SCHEMA IF EXISTS auth CASCADE;");
  await pool.query(baselineCompleto());
  await pool.query("ALTER ROLE service_role BYPASSRLS;");
  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS clients_id_company_unique ON public.clients (id, company_id);
    ALTER TABLE public.data_history ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    CREATE OR REPLACE FUNCTION public.update_updated_at() RETURNS TRIGGER AS $upd$
      BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $upd$ LANGUAGE plpgsql;
    CREATE OR REPLACE FUNCTION public.fn_capture_history() RETURNS trigger
      LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $h$
      BEGIN RETURN COALESCE(NEW, OLD); END; $h$;
  `);
  await pool.query(`
    ALTER DEFAULT PRIVILEGES IN SCHEMA public
      GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;
  `);
  for (const m of MIGRATIONS_CRM) await pool.query(migrationCrm(m));
  await pool.query(lerSql(M_101B));

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public._migrations (
      name text PRIMARY KEY, checksum text, applied_at timestamptz NOT NULL DEFAULT now())`);
  for (const nome of CADEIA.filter((n) => n !== NOME_102)) {
    await registarNoLedger(nome, ledger[nome]);
  }

  // A 102 corre primeiro, e só depois ganha linha — como o runner faz.
  await pool.query(lerSql(M_102));
  await registarNoLedger(NOME_102, ledger[NOME_102]);

  await semear();

  if (aplicar103) {
    await pool.query(lerSql(M_103));
    await registarNoLedger(NOME_103, checksumLf(NOME_103));
  }
}

