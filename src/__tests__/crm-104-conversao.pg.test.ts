describe("1-3. conversão nominal", () => {
  it("cria cliente e local, e fecha a lead", LENTO, async () => {
    const q = await novoOrcamento(leadA);
    const r = await converter(leadA, q.id);

    expect(r.ja_convertida).toBe(false);
    expect(r.client_id).toBeTruthy();
    expect(r.location_id).toBeTruthy();

    const { rows: cliente } = await pool.query(
      "SELECT name, nif, email, phone, address, type, status, company_id FROM public.clients WHERE id = $1",
      [r.client_id]);
    expect(cliente[0]).toMatchObject({
      name: "Condomínio Alfa",
      nif: "500123456",
      email: "geral@alfa.pt",
      phone: "912345678",
      type: "empresa",
      status: "ativo",
      company_id: EMPRESA,
    });

    const { rows: local } = await pool.query(
      "SELECT name, address, lat, lng, service_type, active, client_id, company_id, hourly_rate FROM public.locations WHERE id = $1",
      [r.location_id]);
    expect(local[0].name).toBe("Condomínio Alfa");
    expect(local[0].address).toBe("Rua da Lead 1, Lisboa");
    expect(local[0].service_type).toBe("manutencao");
    expect(local[0].active).toBe(true);
    expect(local[0].client_id).toBe(r.client_id);
    expect(local[0].company_id).toBe(EMPRESA);
    // 🔴 Preço operacional NÃO inferido: é decisão de quem faz o contrato.
    expect(local[0].hourly_rate).toBeNull();

    const { rows: lead } = await pool.query(
      "SELECT stage, won_at, converted_client_id, converted_location_id, lost_at, lost_reason FROM public.crm_leads WHERE id = $1",
      [leadA]);
    expect(lead[0].stage).toBe("ganho");
    expect(lead[0].won_at).not.toBeNull();
    expect(lead[0].converted_client_id).toBe(r.client_id);
    expect(lead[0].converted_location_id).toBe(r.location_id);
    expect(lead[0].lost_at).toBeNull();
    expect(lead[0].lost_reason).toBeNull();
  });

  it("sem service_type na lead, o local cai no default", LENTO, async () => {
    const lead = await novaLead({ service_type: null });
    const q = await novoOrcamento(lead);
    const r = await converter(lead, q.id);

    const { rows } = await pool.query(
      "SELECT service_type FROM public.locations WHERE id = $1", [r.location_id]);
    expect(rows[0].service_type).toBe("limpeza_regular");
  });

  it("uma lead individual gera um cliente individual", LENTO, async () => {
    const lead = await novaLead({ lead_type: "individual" });
    const q = await novoOrcamento(lead);
    const r = await converter(lead, q.id);

    const { rows } = await pool.query("SELECT type FROM public.clients WHERE id = $1", [r.client_id]);
    expect(rows[0].type).toBe("individual");
  });

  it("uma lead que tinha sido dada como perdida fica coerente ao ganhar", LENTO, async () => {
    const lead = await novaLead();
    await pool.query(
      `UPDATE public.crm_leads
          SET stage = 'perdido', lost_at = now(), lost_reason = 'preco',
              lost_reason_notes = 'achou caro'
        WHERE id = $1`, [lead]);

    const q = await novoOrcamento(lead);
    await converter(lead, q.id);

    const { rows } = await pool.query(
      "SELECT stage, lost_at, lost_reason, lost_reason_notes FROM public.crm_leads WHERE id = $1",
      [lead]);
    expect(rows[0].stage).toBe("ganho");
    expect(rows[0].lost_at).toBeNull();
    expect(rows[0].lost_reason).toBeNull();
    expect(rows[0].lost_reason_notes).toBeNull();
  });
});

