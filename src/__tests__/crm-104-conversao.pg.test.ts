async function novaVisita(leadId: string, address: string | null, over: {
  empresa?: string; lat?: number | null; lng?: number | null;
} = {}): Promise<string> {
  const { rows } = await pool.query(
    `INSERT INTO public.crm_visits (company_id, lead_id, scheduled_start, scheduled_end, address, lat, lng)
     VALUES ($1,$2, now(), now() + interval '1 hour', $3, $4, $5) RETURNING id`,
    [over.empresa ?? EMPRESA, leadId, address, over.lat ?? 41.1, over.lng ?? -8.6],
  );
  return rows[0].id as string;
}

/** Cria um orçamento pela RPC da 103 e deixa-o no estado pedido. */
async function novoOrcamento(leadId: string, opts: {
  visitId?: string | null; estado?: string; empresa?: string;
} = {}): Promise<{ id: string; numero: string }> {
  const empresa = opts.empresa ?? EMPRESA;
  const { rows } = await pool.query(
    `SELECT * FROM public.create_crm_quote_with_items(
       $1,$2,NULL,$3,'ORC',$4,CURRENT_DATE,CURRENT_DATE + 30,
       'pontual',0,true,23,NULL,NULL,NULL,NULL,NULL,$5,$6::jsonb)`,
    [
      empresa, leadId, opts.visitId ?? null, ANO,
      empresa === EMPRESA ? GESTORA : GESTORA_OUTRA,
      JSON.stringify([{ description: "Limpeza", quantity: 1, unit: "servico", unit_price: 100 }]),
    ],
  );
  const id = rows[0].quote_id as string;
  const numero = rows[0].quote_number as string;

  const estado = opts.estado ?? "aceite";
  const actor = empresa === EMPRESA ? GESTORA : GESTORA_OUTRA;
  if (estado !== "rascunho") {
    await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,'enviado',NULL)", [empresa, id, actor]);
    if (estado !== "enviado") {
      await pool.query("SELECT public.set_crm_quote_status($1,$2,$3,$4,NULL)", [empresa, id, actor, estado]);
    }
  }
  return { id, numero };
}

async function converter(
  leadId: string,
  quoteId: string | null,
  over: { empresa?: string; actor?: string } = {},
): Promise<{ client_id: string; location_id: string; ja_convertida: boolean }> {
  const { rows } = await pool.query(
    "SELECT * FROM public.convert_crm_lead_atomic($1,$2,$3,$4)",
    [over.empresa ?? EMPRESA, leadId, over.actor ?? GESTORA, quoteId],
  );
  return rows[0];
}

/** Fotografia do que uma recusa não pode ter mudado. */
async function fotografia(leadId: string, quoteId: string) {
  const { rows: c } = await pool.query("SELECT count(*)::int AS n FROM public.clients");
  const { rows: l } = await pool.query("SELECT count(*)::int AS n FROM public.locations");
  const { rows: i } = await pool.query("SELECT count(*)::int AS n FROM public.crm_lead_interactions");
  const { rows: lead } = await pool.query(
    "SELECT stage, won_at, converted_client_id, converted_location_id FROM public.crm_leads WHERE id = $1",
    [leadId]);
  const { rows: q } = await pool.query(
    "SELECT lead_id, client_id, status, source_lead_id FROM public.crm_quotes WHERE id = $1",
    [quoteId]);
  return { clients: c[0].n, locations: l[0].n, interactions: i[0].n, lead: lead[0], quote: q[0] };
}

