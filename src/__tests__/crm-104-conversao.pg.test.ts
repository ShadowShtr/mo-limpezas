// ============================================================================
// 104 — a conversão de uma lead, contra Postgres real
// ============================================================================
//
// 🔴 O palco é a cadeia como está EM PRODUÇÃO hoje:
//
//        baseline canónico + 101 + 101a + 101b + 102 + 103 + 103a  →  104
//
//    A 103a entrou no ledger a 21/09. A 104 depende das duas: converte a
//    partir de um orçamento aceite, e o orçamento é da 103.
//
// ---------------------------------------------------------------------------
// O que só Postgres real responde
// ---------------------------------------------------------------------------
//
//   · duas conversões simultâneas da mesma lead criam UM cliente e UM local;
//   · uma recusa não deixa vestígio nenhum — nem cliente, nem local, nem
//     linha de timeline, nem lead tocada;
//   · a FK composta de três colunas recusa mesmo um par (cliente, local) que
//     as duas FKs da 101 aceitariam;
//   · a ACL e o `search_path` ficam como a 103a ensinou, desde o primeiro dia.
//
// Nenhuma destas se prova com mocks.
// ============================================================================

